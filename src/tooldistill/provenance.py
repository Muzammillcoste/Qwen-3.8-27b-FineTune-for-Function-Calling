"""Teacher-source provenance derived ONLY from original source IDs (spec B1, test #7).

The dataset card states ids 0..33658 were generated by DeepSeek-V2-Chat and the remainder by
Mixtral-8x22B-Instruct. Provenance is never inferred from a local/shuffled row position.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable
from dataclasses import dataclass
from typing import Any

from .schemas import UNKNOWN_TEACHER

DEFAULT_RULES: tuple[dict[str, Any], ...] = (
    {"teacher_source": "deepseek-v2-chat", "min_id": 0, "max_id": 33658},
    {"teacher_source": "mixtral-8x22b-instruct", "min_id": 33659, "max_id": 59999},
)
DEFAULT_EXPECTED_COUNTS = {"deepseek-v2-chat": 33659, "mixtral-8x22b-instruct": 26341}


@dataclass(frozen=True)
class ParsedId:
    value: int | None
    note: str | None  # e.g. "id_coerced_from_string", "id_invalid_type"


def parse_original_id(raw: Any) -> ParsedId:
    """Accept ints and digit strings. Reject bools/floats/other (bool is an int subclass)."""
    if isinstance(raw, bool):
        return ParsedId(None, "id_invalid_type:bool")
    if isinstance(raw, int):
        return ParsedId(raw, None)
    if isinstance(raw, str) and raw.strip().isdigit():
        return ParsedId(int(raw.strip()), "id_coerced_from_string")
    if raw is None:
        return ParsedId(None, "id_missing")
    return ParsedId(None, f"id_invalid_type:{type(raw).__name__}")


def teacher_from_id(original_id: int | None, rules: Iterable[dict[str, Any]] = DEFAULT_RULES) -> str:
    if original_id is None:
        return UNKNOWN_TEACHER
    for rule in rules:
        if rule["min_id"] <= original_id <= rule["max_id"]:
            return rule["teacher_source"]
    return UNKNOWN_TEACHER


@dataclass
class SourceCountCheck:
    ok: bool
    observed: dict[str, int]
    expected: dict[str, int]
    message: str


def verify_source_counts(
    teachers: Iterable[str], expected: dict[str, int] | None = None
) -> SourceCountCheck:
    """Compare observed teacher counts with the dataset-card counts. Used on FULL data only."""
    expected = dict(expected or DEFAULT_EXPECTED_COUNTS)
    observed = dict(Counter(teachers))
    mismatches = {
        k: (observed.get(k, 0), v) for k, v in expected.items() if observed.get(k, 0) != v
    }
    unknown = observed.get(UNKNOWN_TEACHER, 0)
    ok = not mismatches and unknown == 0
    if ok:
        msg = "Teacher-source counts match the dataset card."
    else:
        msg = f"Mismatch vs card (observed, expected): {mismatches}; unknown={unknown}"
    return SourceCountCheck(ok, observed, expected, msg)


def check_id_integrity(ids: list[int | None]) -> dict[str, Any]:
    """ID uniqueness / range / gaps summary for inspection reports."""
    present = [i for i in ids if i is not None]
    counts = Counter(present)
    dups = sorted(i for i, c in counts.items() if c > 1)
    out: dict[str, Any] = {
        "n_rows": len(ids),
        "n_missing": len(ids) - len(present),
        "n_unique": len(counts),
        "duplicate_ids": dups[:50],
        "n_duplicate_ids": len(dups),
        "min_id": min(present) if present else None,
        "max_id": max(present) if present else None,
    }
    if present:
        full = set(range(out["min_id"], out["max_id"] + 1))
        missing = sorted(full - set(counts))
        out["n_gaps_in_range"] = len(missing)
        out["gap_examples"] = missing[:50]
    # IDs are trustworthy for provenance only if all present, unique and integer.
    out["id_field_trustworthy"] = bool(present) and out["n_missing"] == 0 and not dups
    return out
